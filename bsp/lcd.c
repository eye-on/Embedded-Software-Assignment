void lcd_gamma_fix(void)
{
    static const uint8_t g[52] = {
        0x00,0x33,0x00,0x34,0x00,0x3A,0x00,0x4A,0x00,0x5C,0x00,0x81,0x00,0xA6,0x00,0xE5,
        0x01,0x13,0x01,0x54,0x01,0x82,0x01,0xCA,0x02,0x00,0x02,0x01,0x02,0x34,0x02,0x67,
        0x02,0x84,0x02,0xA4,0x02,0xB7,0x02,0xCF,0x02,0xDE,0x02,0xF2,0x02,0xFE,0x03,0x10,
        0x03,0x33,0x03,0x6D
    };

    lcd_wr(0xF000, 0x0055);
    lcd_wr(0xF001, 0x00AA);
    lcd_wr(0xF002, 0x0052);
    lcd_wr(0xF003, 0x0008);
    lcd_wr(0xF004, 0x0001);

    for (uint16_t bank = 1; bank <= 6; bank++) {
        uint16_t base = (uint16_t)(0xD000u + (bank << 8));
        for (int i = 0; i < 52; i++) {
            lcd_wr((uint16_t)(base + i), g[i]);
        }
    }

    lcd_wr(0xF004, 0x0000);

    lcd_wr(0x3A00, 0x0055);
}

