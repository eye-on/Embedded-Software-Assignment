static const glyph_t *find_glyph(char c)
{
    for (unsigned i = 0; i < sizeof(g_font) / sizeof(g_font[0]); i++) {
        if (g_font[i].c == c) return &g_font[i];
    }
    return &g_font[7];
}

void lcd_draw_text(uint16_t x, uint16_t y, const char *s,
                          uint16_t scale, uint16_t fg)
{
    while (*s) {
        const glyph_t *g = find_glyph(*s);

        for (int r = 0; r < 7; r++) {
            for (int c = 0; c < 5; c++) {
                if (g->rows[r] & (0x10u >> c)) {
                    uint16_t px = x + (uint16_t)(c * scale);
                    uint16_t py = y + (uint16_t)(r * scale);
                    lcd_fill_rect(px, py,
                                  px + scale - 1, py + scale - 1, fg);
                }
            }
        }

        x += (uint16_t)(6 * scale);
        s++;
    }
}

void lcd_draw_uint(uint16_t x, uint16_t y, uint32_t v,
                          uint16_t scale, uint16_t fg)
{
    char t[11];
    char buf[12];
    int m = 0, n = 0;

    if (v == 0) {
        t[m++] = '0';
    } else {
        while (v) { t[m++] = (char)('0' + (v % 10u)); v /= 10u; }
    }
    while (m) buf[n++] = t[--m];
    buf[n] = 0;

    lcd_draw_text(x, y, buf, scale, fg);
}

void lcd_draw_int(uint16_t x, uint16_t y, int32_t v,
                         uint16_t scale, uint16_t fg)
{
    if (v < 0) {
        lcd_draw_text(x, y, "-", scale, fg);
        x = (uint16_t)(x + 6 * scale);
        v = -v;
    }
    lcd_draw_uint(x, y, (uint32_t)v, scale, fg);
}

void lcd_draw_fixed(uint16_t x, uint16_t y, uint32_t centi,
                    uint16_t scale, uint16_t fg)
{
    char buf[24];

    sprintf(buf, "%lu.%02lu",
            (unsigned long)(centi / 100u),
            (unsigned long)(centi % 100u));

    lcd_draw_text(x, y, buf, scale, fg);
}

void lcd_backlight(int on)
{
    RCC_AHB1ENR |= (1u << 1);

    GPIOB_MODER = (GPIOB_MODER & ~((3u << 28) | (3u << 30))) |
                  ((1u << 28) | (1u << 30));

    if (on) GPIOB_ODR |=  (1u << 14) | (1u << 15);
    else    GPIOB_ODR &= ~((1u << 14) | (1u << 15));
}
