#include "sys.h"
#include "lcd.h"

static inline void lcd_cmd(uint16_t c) { LCD_REG = c; }

void port_af(volatile uint32_t *moder, volatile uint32_t *ospeedr,
                    volatile uint32_t *afrl, volatile uint32_t *afrh,
                    const uint8_t *pins, int n)
{
    for (int i = 0; i < n; i++) {
        uint32_t p = pins[i];
        *moder   = (*moder   & ~(3u << (p * 2))) | (2u << (p * 2));
        *ospeedr = (*ospeedr & ~(3u << (p * 2))) | (3u << (p * 2));

        if (p < 8) {
            *afrl = (*afrl & ~(0xFu << (p * 4))) | (12u << (p * 4));
        } else {
            uint32_t s = (p - 8) * 4;
            *afrh = (*afrh & ~(0xFu << s)) | (12u << s);
        }
    }
}

void fsmc_init(void)
{
    static const uint8_t d_pins[]  = {0, 1, 4, 5, 8, 9, 10, 14, 15};
    static const uint8_t e_pins[]  = {7, 8, 9, 10, 11, 12, 13, 14, 15};

    RCC_AHB1ENR |= (1u << 3) | (1u << 4) | (1u << 5) | (1u << 6);
    RCC_AHB3ENR |= (1u << 0);

    port_af(&GPIOD_MODER, &GPIOD_OSPEEDR, &GPIOD_AFRL, &GPIOD_AFRH, d_pins, 9);
    port_af(&GPIOE_MODER, &GPIOE_OSPEEDR, &GPIOE_AFRL, &GPIOE_AFRH, e_pins, 9);

    GPIOF_MODER   &= ~(3u << 24); GPIOF_MODER   |= (2u << 24);
    GPIOF_OSPEEDR &= ~(3u << 24); GPIOF_OSPEEDR |= (3u << 24);
    GPIOF_AFRH    &= ~(0xFu << 16); GPIOF_AFRH   |= (12u << 16);

    GPIOG_MODER   &= ~(3u << 24); GPIOG_MODER   |= (2u << 24);
    GPIOG_OSPEEDR &= ~(3u << 24); GPIOG_OSPEEDR |= (3u << 24);
    GPIOG_AFRH    &= ~(0xFu << 16); GPIOG_AFRH   |= (12u << 16);

    FSMC_BCR4 = (1u << 0) | (1u << 4) | (1u << 12);

    FSMC_BTR4 = 12u | (200u << 8);
}

static inline void lcd_wr(uint16_t reg, uint16_t val)
{
    LCD_REG = reg;
    LCD_RAM = val;
}

static inline uint16_t lcd_rd(void) { return LCD_RAM; }

void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    lcd_wr(0x2A00, x0 >> 8); lcd_wr(0x2A01, x0 & 0xFF);
    lcd_wr(0x2A02, x1 >> 8); lcd_wr(0x2A03, x1 & 0xFF);
    lcd_wr(0x2B00, y0 >> 8); lcd_wr(0x2B01, y0 & 0xFF);
    lcd_wr(0x2B02, y1 >> 8); lcd_wr(0x2B03, y1 & 0xFF);
    lcd_cmd(0x2C00);
}

void lcd_fill_rect(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1,
                          uint16_t color)
{
    uint32_t n = (uint32_t)(x1 - x0 + 1) * (uint32_t)(y1 - y0 + 1);
    lcd_set_window(x0, y0, x1, y1);
    for (uint32_t i = 0; i < n; i++) {
        LCD_RAM = color;
    }
}

uint16_t lcd_read_id(void)
{
    lcd_wr(0xF000, 0x0055);
    lcd_wr(0xF001, 0x00AA);
    lcd_wr(0xF002, 0x0052);
    lcd_wr(0xF003, 0x0008);
    lcd_wr(0xF004, 0x0001);

    lcd_cmd(0xC500);
    uint16_t id = (uint16_t)(lcd_rd() << 8);
    lcd_cmd(0xC501);
    id |= (uint16_t)(lcd_rd() & 0x00FF);
    return id;
}

